// Make the buy button say what you get.
//
//   node _tools/set-cta-labels.js --preview    # every label, current -> proposed
//   node _tools/set-cta-labels.js              # dry run, just the count
//   node _tools/set-cta-labels.js --write
//   node _tools/set-cta-labels.js --remove --write   # back to "Buy & Download"
//
// WHY THIS EXISTS
// ---------------
// SEPT-10-PLAN.md Phase 5 measured it: 89 of 94 CTAs read "Buy & Download". The
// three club pages instead read "Get All 50 Games", "Get All 25 Games", "Get All
// 10 Games" -- they say what is in the box, and that is the pattern worth
// spreading. A generic verb asks for a commitment; a specific one describes a
// thing you are about to have.
//
// WHERE THE NUMBER COMES FROM
// ---------------------------
// assets/js/store-facets.js, generated by build-store-facets.js, which reads each
// count off that product's own page rather than out of a map. This tool never
// derives a count itself: one source, and it is in the Monday drift loop.
//
// TWO SAFETY RULES, BOTH LEARNED FROM THE FIRST --preview
// 1. A product the facets cannot speak for is LEFT ALONE, not reset to the
//    default. The first draft returned null and then fell through to
//    "Buy & Download", which would have overwritten "Buy on Amazon" on p18,
//    "Buy Lifetime Access" on p65 and "Book Now" on p140 with something less
//    true than what was already there.
// 2. Only a button still reading the generic default is rewritten. A page whose
//    label is already specific is one somebody chose; churning it gains nothing
//    and loses their wording.
//
// So the four Q&A question banks, p189, and anything staged without a tile keep
// what they have. There is no countable number of game nights behind them and a
// label is not worth inventing one for.
//
// No em-dashes: these are the most-read six words on the site.
const fs = require("fs");
const path = require("path");

const REPO = path.resolve(__dirname, "..");
const args = process.argv.slice(2);
const WRITE = args.includes("--write");
const REMOVE = args.includes("--remove");
const PREVIEW = args.includes("--preview");
const ONLY = args.filter((a) => /^p\d+$/.test(a));

const DEFAULT = "Buy &amp; Download";

// Read the generated facets textually rather than executing them, the same way
// bake-buy-links.js reads ls-links.js.
const gen = fs.readFileSync(path.join(REPO, "assets", "js", "store-facets.js"), "utf8");
const FACETS = JSON.parse((gen.match(/window\.FCE_FACETS = ([\s\S]*?);\n/) || [])[1] || "{}");

// Hand overrides win over anything derived below, and are the place for a
// product the facets cannot reach. Each one is a deliberate exception.
const LABELS = {
  // Consult Hour has no tile, so no facets, and it was reading "Buy & Download"
  // for something add-delivery-note.js already knows is a booking, not a
  // download. p140 (Zoom Party) is the same product type and already says
  // "Book Now", which is left as it is.
  p137: "Book a Call",
};

function labelFor(pid, f) {
  if (LABELS[pid]) return LABELS[pid];
  if (!f) return null;
  // Amazon titles are wired through .kdp-buy and already say "Buy on Amazon";
  // a booking, the shirt and the licence all carry their own wording already.
  if (f.delivery !== "download") return null;

  const n = f.games;
  if (!n) return null;
  // A pre-made trivia show is a night you host, not a game you play.
  const noun = f.type === "trivia-show" ? "Show" : "Game";
  if (n === 1) return "Download the " + noun;
  // "Get All 2 Games" is clunky where English already has a word for it.
  if (n === 2) return "Get Both " + noun + "s";
  return "Get All " + n + " " + noun + "s";
}

const products = [];
for (const dir of fs.readdirSync(path.join(REPO, "store"))) {
  if (!/^p\d+$/.test(dir)) continue;
  if (ONLY.length && !ONLY.includes(dir)) continue;
  const full = path.join(REPO, "store", dir);
  if (!fs.statSync(full).isDirectory()) continue;
  for (const f of fs.readdirSync(full)) {
    if (f.endsWith(".html")) products.push([dir, path.join(full, f)]);
  }
}
products.sort((a, b) => a[1].localeCompare(b[1]));

// The inner span of the buy button, scoped to the buy div so nothing else on the
// page can match.
const BUY_RE = /(<div id="wsite-com-product-buy">[\s\S]*?<span class="wsite-button-inner">)([\s\S]*?)(<\/span>)/;

let changed = 0, kept = 0, skipped = 0, bespoke = 0;
const rows = [];

for (const [pid, file] of products) {
  let html = fs.readFileSync(file, "utf8");
  const before = html;
  const rel = path.relative(REPO, file);

  if (/http-equiv="refresh"/i.test(html)) { skipped++; continue; }
  const m = html.match(BUY_RE);
  if (!m) { skipped++; continue; }

  const current = m[2].trim();
  const mine = labelFor(pid, FACETS[pid]);
  // --remove only undoes labels this tool would itself produce, so a bespoke
  // one written by a person survives it.
  const want = REMOVE ? (current === mine ? DEFAULT : current) : (mine || current);
  rows.push([pid, current, want]);

  // Never overwrite a label that is already specific.
  if (!REMOVE && current !== DEFAULT && current !== want) {
    rows[rows.length - 1][2] = current;
    bespoke++; continue;
  }
  if (current === want) { kept++; continue; }
  // A function replacer, always: a label is prose today but "$1" in a
  // replacement string is a backreference, and this repo has been bitten twice.
  html = html.replace(BUY_RE, (all, open, txt, close) => open + want + close);
  if (html === before) { kept++; continue; }
  changed++;
  if (!PREVIEW) console.log(`  ${WRITE ? "updated" : "would update"}: ${rel}  "${current}" -> "${want}"`);
  if (WRITE) fs.writeFileSync(file, html);
}

if (PREVIEW) {
  for (const [pid, current, want] of rows) {
    const mark = current === want ? "   " : " * ";
    console.log(`${mark}${pid.padEnd(6)} ${current.padEnd(24)} ${current === want ? "" : "-> " + want}`);
  }
  console.log("\n* = would change");
}

console.log(`\nproduct pages     : ${products.length}`);
console.log(`already correct   : ${kept}`);
console.log(`bespoke, left as is: ${bespoke}`);
console.log(`skipped           : ${skipped}   (redirect stubs and the Amazon page)`);
console.log(`${WRITE ? "updated" : "would update"}: ${changed} page(s)`);
if (!WRITE && changed) console.log("re-run with --write");
